-- ============================================================================
-- INSTALAR EM NOVA EMPRESA — Multicanal - Atendimento WhatsApp
-- ============================================================================
-- Script unificado: cria as 12 tabelas MC_ZAP_*, indices e constraints.
--
-- SCHEMA: criado no schema de QUEM CONECTA (sem prefixo). Rode conectado
--         como o usuario dono (ex.: MCLABS). O usuario eh criado ANTES pelo
--         DBA via 00_create_schema.sql (precisa de SYS).
--
-- COMO RODAR:
--   sqlplus MCLABS/senha@//172.16.100.8:1521/MCANAL @instalar_em_nova_empresa.sql
--
-- Fusoes (consolidacao 16 -> 12 tabelas):
--   - MC_ZAP_MIDIA   -> colunas de midia em MC_ZAP_MENSAGEM (1 arquivo/msg)
--   - MC_ZAP_OPTLOG  -> registrado em MC_ZAP_AUDITORIA (estado atual em MC_ZAP_CONTATO)
--   - MC_ZAP_CONVERSA_TAG -> coluna JSON TAGS em MC_ZAP_CONVERSA
--   - MC_ZAP_NOTA    -> mensagens com DIRECAO='nota' em MC_ZAP_MENSAGEM
--
-- IDEMPOTENCIA: NAO eh idempotente (rodar 2x gera erro). REQUER Oracle 12c+.
-- ============================================================================

-- (Script portável: sem comandos SQL*Plus — roda em SQL*Plus, SQLcl,
--  SQL Developer e na Command Window do PL/SQL Developer.)

-- 1) Números de WhatsApp (multi-número). Um app/webhook atende vários.
CREATE TABLE MC_ZAP_NUMERO (
  ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PHONE_NUMBER_ID   VARCHAR2(40) NOT NULL,
  DISPLAY_PHONE     VARCHAR2(30),
  WABA_ID           VARCHAR2(40),
  NOME_EXIBICAO     VARCHAR2(120),
  DEPARTAMENTO      VARCHAR2(60),
  CODFILIAL         NUMBER,
  QUALITY_RATING    VARCHAR2(10),
  MESSAGING_TIER    VARCHAR2(20),
  LIMITE_DIARIO     NUMBER DEFAULT 250 NOT NULL,   -- teto de destinatários/dia em campanha (Meta: número novo ~250/dia)
  PERMITE_ATIVO     CHAR(1) DEFAULT 'S' NOT NULL,  -- pode originar disparo ativo (campanha / Nova conversa)
  ATIVO             CHAR(1) DEFAULT 'S' NOT NULL,
  CRIADO_EM         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_MCZAP_NUM_PNID UNIQUE (PHONE_NUMBER_ID),
  CONSTRAINT CK_MCZAP_NUM_ATIVO CHECK (ATIVO IN ('S','N')),
  CONSTRAINT CK_MCZAP_NUM_PERMATIVO CHECK (PERMITE_ATIVO IN ('S','N'))
);

-- 2) Atendentes / usuários (RBAC). Vincula à matrícula do MC_SENHAS.
CREATE TABLE MC_ZAP_ATENDENTE (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  MATRICULA    NUMBER NOT NULL,
  NOME         VARCHAR2(120),
  PAPEL        VARCHAR2(20) DEFAULT 'ATENDENTE' NOT NULL, -- ADMIN/SUPERVISOR/ATENDENTE/AUDITOR
  CODFILIAL    NUMBER,
  ATIVO        CHAR(1) DEFAULT 'S' NOT NULL,
  CRIADO_EM    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_MCZAP_ATD_MAT UNIQUE (MATRICULA),
  CONSTRAINT CK_MCZAP_ATD_PAPEL CHECK (PAPEL IN ('ADMIN','SUPERVISOR','ATENDENTE','AUDITOR')),
  CONSTRAINT CK_MCZAP_ATD_ATIVO CHECK (ATIVO IN ('S','N'))
);

-- 3) Templates (HSM) — gerenciados pela plataforma e submetidos à Meta.
CREATE TABLE MC_ZAP_TEMPLATE (
  ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOME          VARCHAR2(100) NOT NULL,
  IDIOMA        VARCHAR2(10)  DEFAULT 'pt_BR' NOT NULL,
  CATEGORIA     VARCHAR2(20),                     -- UTILITY/MARKETING/AUTHENTICATION/SERVICE
  STATUS_META   VARCHAR2(20) DEFAULT 'PENDENTE',  -- PENDENTE/APROVADO/REJEITADO
  CORPO         CLOB,                             -- texto com {{1}},{{2}}...
  VARIAVEIS     CLOB,                             -- JSON: descrição/exemplo de cada variável
  BOTOES        CLOB,                             -- JSON: quick reply / CTA
  WABA_ID       VARCHAR2(40),
  CRIADO_POR    NUMBER,
  CRIADO_EM     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  ATUALIZADO_EM TIMESTAMP,
  CONSTRAINT UQ_MCZAP_TPL UNIQUE (NOME, IDIOMA),
  CONSTRAINT FK_MCZAP_TPL_ATD FOREIGN KEY (CRIADO_POR) REFERENCES MC_ZAP_ATENDENTE (ID)
);

-- 4) Contatos (dedup por telefone E.164 sem '+'). Estado atual de opt-in aqui.
CREATE TABLE MC_ZAP_CONTATO (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TELEFONE     VARCHAR2(20)  NOT NULL,
  WA_ID        VARCHAR2(30),
  NOME_PERFIL  VARCHAR2(200),
  CODCLI       NUMBER,                            -- vínculo PCCLIENT
  CGCENT       VARCHAR2(20),
  OPTIN        CHAR(1) DEFAULT 'N' NOT NULL,
  OPTIN_ORIGEM VARCHAR2(60),
  OPTIN_EM     TIMESTAMP,
  CRIADO_EM    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_MCZAP_CONTATO_TEL UNIQUE (TELEFONE),
  CONSTRAINT CK_MCZAP_CONTATO_OPTIN CHECK (OPTIN IN ('S','N'))
);
CREATE INDEX IX_MCZAP_CONTATO_CODCLI ON MC_ZAP_CONTATO (CODCLI);

-- 5) Catálogo de tags/etiquetas (a atribuição fica na coluna JSON da conversa).
CREATE TABLE MC_ZAP_TAG (
  ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOME   VARCHAR2(60) NOT NULL,
  COR    VARCHAR2(9),
  CONSTRAINT UQ_MCZAP_TAG_NOME UNIQUE (NOME)
);

-- 6) Conversas (uma por contato/número; janela de 24h; tags embutidas em JSON).
CREATE TABLE MC_ZAP_CONVERSA (
  ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CONTATO_ID        NUMBER NOT NULL,
  NUMERO_ID         NUMBER,
  ATENDENTE_ID      NUMBER,
  STATUS            VARCHAR2(20) DEFAULT 'aberta' NOT NULL, -- aberta/pendente/resolvida
  TAGS              VARCHAR2(1000),                          -- JSON: array de IDs de tag
  JANELA_EXPIRA_EM  TIMESTAMP,
  ULTIMA_MSG_EM     TIMESTAMP,
  CRIADO_EM         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_MCZAP_CONV_CONTATO FOREIGN KEY (CONTATO_ID)   REFERENCES MC_ZAP_CONTATO (ID),
  CONSTRAINT FK_MCZAP_CONV_NUMERO  FOREIGN KEY (NUMERO_ID)    REFERENCES MC_ZAP_NUMERO (ID),
  CONSTRAINT FK_MCZAP_CONV_ATD     FOREIGN KEY (ATENDENTE_ID) REFERENCES MC_ZAP_ATENDENTE (ID),
  CONSTRAINT CK_MCZAP_CONV_TAGS    CHECK (TAGS IS NULL OR TAGS IS JSON)
);
CREATE INDEX IX_MCZAP_CONV_CONTATO ON MC_ZAP_CONVERSA (CONTATO_ID);
CREATE INDEX IX_MCZAP_CONV_STATUS  ON MC_ZAP_CONVERSA (STATUS);
CREATE INDEX IX_MCZAP_CONV_ATD     ON MC_ZAP_CONVERSA (ATENDENTE_ID);

-- 7) Mensagens (in/out/nota). Histórico permanente. Mídia embutida. Dedup por WAMID.
CREATE TABLE MC_ZAP_MENSAGEM (
  ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CONVERSA_ID   NUMBER,
  CONTATO_ID    NUMBER,
  NUMERO_ID     NUMBER,
  ATENDENTE_ID  NUMBER,                           -- quem enviou (out) ou autor da nota
  TEMPLATE_ID   NUMBER,                           -- se 'out' via template
  WAMID         VARCHAR2(128),
  DIRECAO       VARCHAR2(4) NOT NULL,             -- 'in' | 'out' | 'nota'
  TIPO          VARCHAR2(30),                     -- text/template/image/document/audio/video/...
  CONTEUDO      CLOB,                             -- texto, legenda, ou JSON do conteúdo
  STATUS        VARCHAR2(20),                     -- sent/delivered/read/failed (out)
  ERRO_CODIGO   VARCHAR2(20),
  TS            TIMESTAMP,
  -- mídia embutida (antes MC_ZAP_MIDIA):
  MEDIA_ID      VARCHAR2(128),
  MIME_TYPE     VARCHAR2(120),
  NOME_ARQUIVO  VARCHAR2(260),
  MIDIA_CAMINHO VARCHAR2(500),                    -- caminho no servidor de arquivos (Windows)
  MIDIA_TAMANHO NUMBER,
  MIDIA_SHA256  VARCHAR2(64),
  CRIADO_EM     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_MCZAP_MSG_WAMID UNIQUE (WAMID),
  CONSTRAINT CK_MCZAP_MSG_DIR CHECK (DIRECAO IN ('in','out','nota')),
  CONSTRAINT FK_MCZAP_MSG_CONV    FOREIGN KEY (CONVERSA_ID)  REFERENCES MC_ZAP_CONVERSA (ID),
  CONSTRAINT FK_MCZAP_MSG_CONTATO FOREIGN KEY (CONTATO_ID)   REFERENCES MC_ZAP_CONTATO (ID),
  CONSTRAINT FK_MCZAP_MSG_NUMERO  FOREIGN KEY (NUMERO_ID)    REFERENCES MC_ZAP_NUMERO (ID),
  CONSTRAINT FK_MCZAP_MSG_ATD     FOREIGN KEY (ATENDENTE_ID) REFERENCES MC_ZAP_ATENDENTE (ID),
  CONSTRAINT FK_MCZAP_MSG_TPL     FOREIGN KEY (TEMPLATE_ID)  REFERENCES MC_ZAP_TEMPLATE (ID)
);
CREATE INDEX IX_MCZAP_MSG_STATUS ON MC_ZAP_MENSAGEM (STATUS);
CREATE INDEX IX_MCZAP_MSG_CONV   ON MC_ZAP_MENSAGEM (CONVERSA_ID);
CREATE INDEX IX_MCZAP_MSG_TS     ON MC_ZAP_MENSAGEM (TS);

-- 8) Respostas rápidas (canned responses).
CREATE TABLE MC_ZAP_RESPOSTA_RAPIDA (
  ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ATALHO      VARCHAR2(40),
  TITULO      VARCHAR2(120),
  CONTEUDO    CLOB,
  CRIADO_POR  NUMBER,
  CRIADO_EM   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_MCZAP_RR_ATD FOREIGN KEY (CRIADO_POR) REFERENCES MC_ZAP_ATENDENTE (ID)
);

-- 9) Campanhas de disparo (cobrança em lote — Fase 6).
CREATE TABLE MC_ZAP_CAMPANHA (
  ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOME          VARCHAR2(160) NOT NULL,
  NUMERO_ID     NUMBER,
  TEMPLATE_ID   NUMBER,
  TEMPLATE_NOME VARCHAR2(120),                     -- snapshot do template aprovado (Graph)
  LANG          VARCHAR2(10) DEFAULT 'pt_BR',
  SEGMENTO      CLOB,                              -- JSON {sql, telefoneCol, variaveis[]}
  AGENDAMENTO   TIMESTAMP,
  STATUS        VARCHAR2(20) DEFAULT 'rascunho' NOT NULL, -- rascunho/enviando/pausada/concluida
  TOTAL         NUMBER DEFAULT 0 NOT NULL,         -- destinatários preparados
  ENVIADOS      NUMBER DEFAULT 0 NOT NULL,         -- progresso (denormalizado p/ o monitor)
  RATE_POR_SEG  NUMBER DEFAULT 10 NOT NULL,        -- throttle de envio
  JANELA_INICIO VARCHAR2(5) DEFAULT '08:00' NOT NULL, -- horário comercial
  JANELA_FIM    VARCHAR2(5) DEFAULT '20:00' NOT NULL,
  PAUSA_MOTIVO  VARCHAR2(200),
  RETOMA_EM     TIMESTAMP,                         -- backoff: não processa antes disto
  CRIADO_POR    NUMBER,
  CRIADO_EM     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  ATUALIZADO_EM TIMESTAMP,
  CONSTRAINT FK_MCZAP_CAMP_NUM FOREIGN KEY (NUMERO_ID)   REFERENCES MC_ZAP_NUMERO (ID),
  CONSTRAINT FK_MCZAP_CAMP_TPL FOREIGN KEY (TEMPLATE_ID) REFERENCES MC_ZAP_TEMPLATE (ID),
  CONSTRAINT FK_MCZAP_CAMP_ATD FOREIGN KEY (CRIADO_POR)  REFERENCES MC_ZAP_ATENDENTE (ID)
);
CREATE INDEX IX_MCZAP_CAMP_STATUS ON MC_ZAP_CAMPANHA (STATUS);

-- 10) Item de campanha (1 por destinatário).
CREATE TABLE MC_ZAP_CAMPANHA_ITEM (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CAMPANHA_ID  NUMBER NOT NULL,
  CONTATO_ID   NUMBER,
  TELEFONE     VARCHAR2(20),
  VARIAVEIS    CLOB,                              -- JSON array ["v1","v2"] (ordem = {{1}},{{2}})
  WAMID        VARCHAR2(128),
  STATUS       VARCHAR2(20) DEFAULT 'pendente',   -- pendente/enviando_item/enviado/entregue/lido/falha/optout
  ERRO_CODIGO  VARCHAR2(20),
  CUSTO        NUMBER(10,4),
  TENTATIVAS   NUMBER DEFAULT 0 NOT NULL,
  ENVIADO_EM   TIMESTAMP,
  CONSTRAINT FK_MCZAP_CI_CAMP    FOREIGN KEY (CAMPANHA_ID) REFERENCES MC_ZAP_CAMPANHA (ID),
  CONSTRAINT FK_MCZAP_CI_CONTATO FOREIGN KEY (CONTATO_ID)  REFERENCES MC_ZAP_CONTATO (ID),
  CONSTRAINT UQ_MCZAP_CI_CAMP_TEL UNIQUE (CAMPANHA_ID, TELEFONE) -- dedup atômico no preparar
);
CREATE INDEX IX_MCZAP_CI_CAMP     ON MC_ZAP_CAMPANHA_ITEM (CAMPANHA_ID);
CREATE INDEX IX_MCZAP_CI_STATUS   ON MC_ZAP_CAMPANHA_ITEM (STATUS);
CREATE INDEX IX_MCZAP_CI_WAMID    ON MC_ZAP_CAMPANHA_ITEM (WAMID);          -- updateStatus do webhook
CREATE INDEX IX_MCZAP_CI_DISPATCH ON MC_ZAP_CAMPANHA_ITEM (CAMPANHA_ID, STATUS); -- varre lote

-- 11) Auditoria (trilha genérica; absorve o histórico de opt-in/opt-out — LGPD).
--     Opt-in/out: ACAO='optin'/'optout', ENTIDADE='contato', ENTIDADE_ID=contato,
--     DETALHE=JSON {origem, telefone}.
CREATE TABLE MC_ZAP_AUDITORIA (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ATENDENTE_ID NUMBER,
  MATRICULA    NUMBER,
  ACAO         VARCHAR2(60),                      -- envio/atribuicao/optin/optout/login...
  ENTIDADE     VARCHAR2(40),                      -- conversa/mensagem/campanha/contato...
  ENTIDADE_ID  NUMBER,
  DETALHE      CLOB,                              -- JSON livre
  IP           VARCHAR2(45),
  CRIADO_EM    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX IX_MCZAP_AUD_ENT  ON MC_ZAP_AUDITORIA (ENTIDADE, ENTIDADE_ID);
CREATE INDEX IX_MCZAP_AUD_ACAO ON MC_ZAP_AUDITORIA (ACAO);
CREATE INDEX IX_MCZAP_AUD_DT   ON MC_ZAP_AUDITORIA (CRIADO_EM);

-- 12) Log bruto de eventos do webhook (append-only, auditoria/replay).
CREATE TABLE MC_ZAP_EVENTO_WEBHOOK (
  ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PHONE_NUMBER_ID VARCHAR2(40),
  PAYLOAD         CLOB NOT NULL,
  ASSINATURA_OK   CHAR(1) DEFAULT 'N' NOT NULL,
  PROCESSADO      CHAR(1) DEFAULT 'N' NOT NULL,
  ERRO            VARCHAR2(4000),
  RECEBIDO_EM     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX IX_MCZAP_EVT_PROC ON MC_ZAP_EVENTO_WEBHOOK (PROCESSADO);

-- ============================================================================
-- VERIFICACAO FINAL — lista as tabelas MC_ZAP_* criadas
-- ============================================================================
SELECT OBJECT_NAME AS TABELA, STATUS
  FROM USER_OBJECTS
 WHERE OBJECT_TYPE = 'TABLE'
   AND OBJECT_NAME LIKE 'MC_ZAP_%'
 ORDER BY OBJECT_NAME;
-- Devem aparecer 12 tabelas MC_ZAP_* acima.
