-- ============================================================================
-- ROW-LEVEL SECURITY — ENABLE + FORCE + policy `isolamento_tenant` por tabela.
-- Sem contexto (tenant_atual() IS NULL) nenhuma linha é visível nem gravável.
-- ============================================================================
DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'departamento','atendente','numero','template','contato','tag','fluxo',
    'conversa','mensagem','resposta_rapida','campanha','campanha_item',
    'auditoria','evento_webhook','atendente_depto','atendente_numero',
    'config','ia_config','ia_turno','ia_autorizado'
  ] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS isolamento_tenant ON %I', t);
    EXECUTE format(
      'CREATE POLICY isolamento_tenant ON %I '
      || 'USING (tenant_id = tenant_atual()) '
      || 'WITH CHECK (tenant_id = tenant_atual())', t);
  END LOOP;
END
$$;

-- tenant: o tenant enxerga a própria linha; contexto NULO (operador/
-- provisionamento) enxerga e administra tudo — APENAS nesta tabela.
ALTER TABLE tenant ENABLE ROW LEVEL SECURITY;
ALTER TABLE tenant FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_proprio  ON tenant;
DROP POLICY IF EXISTS tenant_operador ON tenant;
CREATE POLICY tenant_proprio  ON tenant
  USING (id = tenant_atual());
CREATE POLICY tenant_operador ON tenant
  USING (tenant_atual() IS NULL)
  WITH CHECK (tenant_atual() IS NULL);

-- ============================================================================
-- ROLE DE APLICAÇÃO — sem BYPASSRLS (ver ⚠️ no cabeçalho).
--
-- NOLOGIN de propósito: ninguém conecta como `falatta_app`. O app conecta com
-- o usuário do DATABASE_URL e assume este papel por transação, via
-- `SET LOCAL ROLE falatta_app` (feito por comTenant() em db/pool.js).
-- Sem isso, um usuário-dono com rolbypassrls atravessa todas as policies.
-- ============================================================================
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'falatta_app') THEN
    CREATE ROLE falatta_app NOLOGIN NOBYPASSRLS;
  END IF;
END
$$;

-- Permite ao usuário de conexão assumir o papel (SET ROLE exige ser membro).
GRANT falatta_app TO CURRENT_USER;

GRANT USAGE ON SCHEMA public TO falatta_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO falatta_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO falatta_app;
-- Tabelas/sequências criadas por migrações futuras já nascem acessíveis.
ALTER DEFAULT PRIVILEGES IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO falatta_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO falatta_app;
